from pathlib import Path

import streamlit as st
from PIL import Image, UnidentifiedImageError

from review import ReviewModel, case_report, open_upload

st.set_page_config(page_title="Thyroid ultrasound review", layout="centered")
st.title("Thyroid ultrasound review")
st.write("Inspect the model score and Grad-CAM overlay for a known thyroid nodule.")
EXAMPLES = Path(__file__).parent / "examples"


@st.cache_resource
def load(checkpoint):
    return ReviewModel(checkpoint)


choice = st.selectbox("Classifier", ["MobileNetV3-Small", "ResNet-18"])
checkpoint = (Path(__file__).parent / "runs" /
              ("development" if choice == "MobileNetV3-Small" else "resnet18") / "best.pt")


source = st.radio("Image source", (["Upload an image", "Validation example"] if all((EXAMPLES / f"{n}.jpg").exists() for n in ("000019", "000066")) else ["Upload an image"]), horizontal=True)
if source == "Validation example":
    sample = st.selectbox("TN5000 validation image", ["000019", "000066"])
    image_data = (EXAMPLES / f"{sample}.jpg").read_bytes()
    st.caption("Reference label from TN5000 · " + ("benign" if sample == "000019" else "malignant"))
else:
    uploaded = st.file_uploader("Choose a de-identified B-mode image", type=["png", "jpg", "jpeg"])
    if uploaded is None:
        st.stop()
    image_data = uploaded.getvalue()

try:
    result = load(str(checkpoint)).predict(open_upload(image_data))
except (ValueError, UnidentifiedImageError, OSError, Image.DecompressionBombError) as exc:
    st.error(str(exc))
    st.stop()
col1, col2 = st.columns(2)
col1.image(result["original"], caption="Model input", width="stretch")
col2.image(result["overlay"], caption="Grad-CAM for the malignant class", width="stretch")
c1, c2 = st.columns(2)
c1.metric("Model score", f"{result['score']:.3f}")
c2.metric("Development threshold", f"{result['threshold']:.3f}")
st.write("Score at or above threshold." if result["above_threshold"] else "Score below threshold.")
if result["flat_map"]:
    st.info("The model produced a flat heatmap for this image.")
st.caption(f"Model {result['architecture']} · Checkpoint {result['checkpoint']}. The score is uncalibrated.")
st.download_button("Download research report", case_report(result), "thyroid_model_review.docx",
                   mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document")
if source == "Validation example":
    st.caption("Source image by Zhang et al., TN5000 (2025), CC BY 4.0. The overlay is generated by this model.")
